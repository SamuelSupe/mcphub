const textSources = new WeakMap();
const attributeSources = new WeakMap();
let locale = readStoredLocale();

function readStoredLocale() {
  try {
    return localStorage.getItem("mcphub.admin.locale") === "en" ? "en" : "zh-CN";
  } catch (_) {
    return "zh-CN";
  }
}

export function getLocale() {
  return locale;
}

export function setLocale(value) {
  locale = value === "en" ? "en" : "zh-CN";
  document.documentElement.lang = locale;
  try { localStorage.setItem("mcphub.admin.locale", locale); } catch (_) {}
}

export function t(source, values = {}) {
  const template = locale === "en" ? english[source] || source : source;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, key) => String(values[key] ?? ""));
}

export function apiErrorMessage(error, fallback = "请求失败") {
  if (locale === "en") return apiErrors[error?.code] || english[fallback] || "Request failed.";
  return error?.message || fallback;
}

export function translateDOM(root = document) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    if (node.parentElement?.closest("script, style")) continue;
    const current = node.nodeValue || "";
    const trimmed = current.trim();
    if (!trimmed) continue;
    let source = textSources.get(node);
    if (!source || (current !== source.rendered && current !== source.source)) source = { source: trimmed, rendered: current };
    const translated = t(source.source);
    const leading = current.match(/^\s*/)?.[0] || "";
    const trailing = current.match(/\s*$/)?.[0] || "";
    const rendered = `${leading}${translated}${trailing}`;
    node.nodeValue = rendered;
    textSources.set(node, { source: source.source, rendered });
  }

  const elements = root instanceof Element ? [root, ...root.querySelectorAll("*")] : [...root.querySelectorAll("*")];
  for (const element of elements) {
    let sources = attributeSources.get(element) || {};
    for (const name of ["placeholder", "aria-label", "title"]) {
      if (!element.hasAttribute(name)) continue;
      const current = element.getAttribute(name) || "";
      const previous = sources[name];
      const source = !previous || (current !== previous.rendered && current !== previous.source) ? current : previous.source;
      const rendered = t(source);
      element.setAttribute(name, rendered);
      sources = { ...sources, [name]: { source, rendered } };
    }
    attributeSources.set(element, sources);
  }
}
